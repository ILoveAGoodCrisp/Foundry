"""Adapt evaluated Point Cloud geometry to the shared mesh export pipeline."""
from types import SimpleNamespace

from .. import utils


def is_decorator_geometry(instance, preview_sources=None):
    """Placement carriers and their previews belong to the decorator exporter."""
    objects = [instance.object.original]
    if instance.is_instance and instance.parent is not None:
        objects.append(instance.parent.original)
    if any(utils.is_decorator_cloud(ob) for ob in objects):
        return True
    if preview_sources is None:
        preview_sources = utils.decorator_preview_sources()
    return bool(preview_sources.intersection(objects))


def prepare_pointcloud_proxy(proxy, evaluated, meshes, temporary_meshes):
    """Snapshot each generated mesh once, leaving the authored cloud untouched.

    Depsgraph.object_instances exposes meshes generated by a Point Cloud as
    synthetic mesh objects. Their original/instance_object still points to the
    cloud, whose to_mesh() cannot supply this geometry. Use instance.object.
    The carrier itself has no surface; its synthetic components are visited
    separately, including when Realize Instances is used.
    """
    if evaluated.type != 'MESH':
        return False
    key = (proxy.ob, evaluated.data)
    mesh = meshes.get(key)
    if mesh is None:
        mesh = evaluated.data.copy()
        temporary_meshes.add(mesh)
        meshes[key] = mesh
        # Geometry Nodes can introduce materials and attributes that are absent
        # from the source Point Cloud. Keep those and apply its Halo settings.
        source = proxy.ob.data
        for name in tuple(mesh.nwo.keys()):
            del mesh.nwo[name]
        for name, value in source.nwo.items():
            if name != 'face_props':
                mesh.nwo[name] = value
        for prop in source.nwo.face_props:
            utils.face_attributes.copy(source, prop, mesh)
    proxy.type = 'MESH'
    proxy.data = mesh
    proxy.material_slots = tuple(SimpleNamespace(material=mat) for mat in mesh.materials)
    proxy.eval_ob = None
    proxy.modifiers = ()
    return True
